"""Record the video narration from narration.js with the Kokoro text-to-speech voice.

One-time setup:
  python3 -m venv ~/.cache/drone-website-tts/venv
  ~/.cache/drone-website-tts/venv/bin/pip install kokoro-onnx soundfile
  Download kokoro-v1.0.onnx and voices-v1.0.bin from
  https://github.com/thewh1teagle/kokoro-onnx/releases/tag/model-files-v1.0
  into ~/.cache/drone-website-tts/models/  (ffmpeg must also be installed)

Run:
  ~/.cache/drone-website-tts/venv/bin/python tools/make_narration.py

Writes audio/<scene>-<n>.mp3 for every sentence plus audio/timing.js with their lengths.
Only sentences whose spoken text changed are re-recorded.
"""
import hashlib
import json
import re
import subprocess
import tempfile
from pathlib import Path

import soundfile as sf
from kokoro_onnx import Kokoro

ROOT = Path(__file__).resolve().parent.parent
MODELS = Path.home() / ".cache/drone-website-tts/models"
OUT = ROOT / "audio"
VOICE = "af_heart"
SPEED = 0.95


def load_js_object(path, name):
    match = re.search(rf"window\.{name}\s*=\s*(\{{.*\}})\s*;?\s*$", path.read_text(), re.S)
    return json.loads(match.group(1))


def main():
    narration = load_js_object(ROOT / "narration.js", "NARRATION")
    OUT.mkdir(exist_ok=True)
    timing_path = OUT / "timing.js"
    previous = load_js_object(timing_path, "NARRATION_TIMING")["lines"] if timing_path.exists() else {}

    kokoro = None
    lines, scenes = {}, {}
    for scene, sentences in narration.items():
        scenes[scene] = []
        for n, sentence in enumerate(sentences):
            say = sentence if isinstance(sentence, str) else sentence[1]
            name = f"{scene}-{n}"
            digest = hashlib.sha1(f"{VOICE}|{SPEED}|{say}".encode()).hexdigest()[:12]
            mp3 = OUT / f"{name}.mp3"

            if previous.get(name, {}).get("hash") == digest and mp3.exists():
                duration = previous[name]["dur"]
            else:
                kokoro = kokoro or Kokoro(str(MODELS / "kokoro-v1.0.onnx"), str(MODELS / "voices-v1.0.bin"))
                samples, rate = kokoro.create(say, voice=VOICE, speed=SPEED, lang="en-us")
                duration = round(len(samples) / rate, 3)
                with tempfile.NamedTemporaryFile(suffix=".wav") as wav:
                    sf.write(wav.name, samples, rate)
                    subprocess.run(
                        ["ffmpeg", "-y", "-loglevel", "error", "-i", wav.name, "-ac", "1", "-b:a", "96k", str(mp3)],
                        check=True,
                    )
                print(f"recorded {name} ({duration:.1f}s)")

            lines[name] = {"hash": digest, "dur": duration}
            scenes[scene].append(duration)

    for stale in OUT.glob("*.mp3"):
        if stale.stem not in lines:
            stale.unlink()

    data = {"voice": VOICE, "scenes": scenes, "lines": lines}
    timing_path.write_text(
        "// Generated by tools/make_narration.py. Do not edit by hand.\n"
        f"window.NARRATION_TIMING = {json.dumps(data, indent=1)};\n"
    )
    total = sum(sum(d) for d in scenes.values())
    print(f"done: {len(lines)} sentences, {total / 60:.1f} minutes of speech")


if __name__ == "__main__":
    main()
